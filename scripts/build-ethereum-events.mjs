import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Research inputs retain each source's role and the limits of corroboration.
// No price observation, return, model, or scheduled future event is generated.
const reviewDate = '2026-10-24';
const inputs = ['ethereum-protocol-events.json','ethereum-market-events.json'];
const records = (await Promise.all(inputs.map(file=>readFile(new URL(`../research-data/${file}`,import.meta.url),'utf8').then(JSON.parse)))).flat();
const events = records.map(raw=>{
  const {summary, ...event} = raw;
  return {...event,description:event.description||summary,importance:raw.importance==='major'?3:raw.importance==='standard'?2:raw.importance,
    ...(event.datePrecision==='block-timestamp'?{blockHeight:event.facts.block,timestampUtc:event.facts.utcTimestamp,blockHash:event.facts.blockHash}:{}),
    sources:event.sources.map(source=>({...source,publishedAt:source.publishedAt??null,accessedAt:reviewDate})),
  };
}).sort((a,b)=>a.date.localeCompare(b.date)||a.id.localeCompare(b.id));
if(new Set(events.map(event=>event.id)).size!==events.length)throw new Error('Duplicate Ethereum event IDs');
for(const event of events){
  const parsed=Date.parse(`${event.date}T00:00:00Z`);
  if(!Number.isFinite(parsed)||new Date(parsed).toISOString().slice(0,10)!==event.date||event.date>reviewDate)throw new Error(`Invalid or future date: ${event.id}`);
  if(!event.description||!event.dateBasis||!event.crossCheck||!event.limitations?.length||event.sources.length<2)throw new Error(`Incomplete source record: ${event.id}`);
}
const source = `/** Generated by scripts/build-ethereum-events.mjs from reviewed source records.
 * Dates describe historical events, never forecasts or causal price signals.
 * Block timestamps and source calendar days retain their different meanings. */
export const ETHEREUM_EVENTS_REVIEW_DATE = '${reviewDate}';
export const ETHEREUM_EVENT_CATEGORIES = Object.freeze({protocol:'프로토콜',security:'보안 사건',market:'시장·제도',ecosystem:'생태계'});
export const ETHEREUM_EVENT_COLORS = Object.freeze({protocol:'#d8b779',security:'#d3a5c5',market:'#84bce5',ecosystem:'#79c6b6'});
function deepFreeze(value){if(value&&typeof value==='object'&&!Object.isFrozen(value)){for(const child of Object.values(value))deepFreeze(child);Object.freeze(value);}return value;}
export const ETHEREUM_EVENTS = deepFreeze(${JSON.stringify(events,null,2)});

function validDate(value) {
  if (typeof value !== 'string' || !/^\\d{4}-\\d{2}-\\d{2}$/.test(value)) return false;
  const time = Date.parse(value + 'T00:00:00Z');
  return Number.isFinite(time) && new Date(time).toISOString().slice(0,10) === value;
}

/** Filtering never changes the frozen source catalog or manufactures events. */
export function getEthereumEvents({category='all',query='',startDate=null,endDate=null}={}) {
  if(typeof category!=='string'||(category!=='all'&&!Object.hasOwn(ETHEREUM_EVENT_CATEGORIES,category)))throw new RangeError('Unknown Ethereum event category');
  for(const date of [startDate,endDate])if(date!==null&&!validDate(date))throw new RangeError('Invalid Ethereum event date boundary');
  if(startDate&&endDate&&startDate>endDate)throw new RangeError('Reversed Ethereum event date boundaries');
  const terms=String(query??'').trim().toLocaleLowerCase().split(/\\s+/u).filter(Boolean);
  return ETHEREUM_EVENTS.filter(event=>{
    if((category!=='all'&&event.category!==category)||(startDate&&event.date<startDate)||(endDate&&event.date>endDate))return false;
    const searchable=[event.id,event.date,event.label,event.title,event.description,event.detail,ETHEREUM_EVENT_CATEGORIES[event.category],...(event.keywords||[]),...event.sources.map(source=>source.title)].join(' ').toLocaleLowerCase();
    return terms.every(term=>searchable.includes(term));
  });
}
`;
const output = new URL('../dist/ethereum-events.js',import.meta.url);
await writeFile(output,source);
console.log(JSON.stringify({file:fileURLToPath(output),events:events.length,sources:events.reduce((sum,event)=>sum+event.sources.length,0),uniqueUrls:new Set(events.flatMap(event=>event.sources.map(source=>source.url))).size,reviewDate}));
