import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { buildDetailedForecast, evaluateDetailedForecast, DETAILED_SCENARIOS } from '../dist/detailed-forecast.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(await readFile(path.join(root, 'dist/data/btc-daily.json'), 'utf8'));
const options = { asOf: '2026-10-20', referenceDate: '2026-10-22', sampleCount: 128, seed: 20261022 };
const scenarios = DETAILED_SCENARIOS.map(scenario => buildDetailedForecast(data, { ...options, scenario: scenario.id }));
const validation = evaluateDetailedForecast(data, { sampleCount: 64, seed: options.seed });
const sensitivity = [];
const sensitivities = [
  { group: 'block-length', parameters: { blockDays: 14 } },
  { group: 'block-length', parameters: { blockDays: 28 }, baseline: true },
  { group: 'block-length', parameters: { blockDays: 56 } },
  { group: 'seed', parameters: { seed: 20261022 }, baseline: true },
  { group: 'seed', parameters: { seed: 20261023 } },
  { group: 'seed', parameters: { seed: 20261024 } },
  { group: 'volatility', parameters: { volatilityMultiplier: 0.75 } },
  { group: 'volatility', parameters: { volatilityMultiplier: 1 }, baseline: true },
  { group: 'volatility', parameters: { volatilityMultiplier: 1.25 } },
];
for (const setting of sensitivities) {
  const result = setting.baseline ? scenarios[0] : buildDetailedForecast(data, { ...options, ...setting.parameters });
  sensitivity.push({ group: setting.group, parameters: setting.parameters, peakWindow: result.diagnostics.simulatedPeakWindow, lowWindow: result.diagnostics.simulatedLowWindow,
    firstTurnWindows: result.diagnostics.firstTurnWindows,
    mddPct: result.diagnostics.simulatedMddPct, candidateBreakPaths: result.diagnostics.candidateLowBreakPathsBeforePeakReference,
    totalPaths: result.diagnostics.totalPaths, lastPoint: result.path.at(-1), probability: null });
}
const summary = scenarios.map(model => ({ id: model.scenario.id, label: model.scenario.label, asOf: model.asOf, displayEnd: model.displayEnd,
  currentPrice: model.observables.current.price, priceReference: model.assumptions.peakReferencePrice, referencePeakDate: model.nominalClock.effectivePeakDate,
  representativeMaximum: model.diagnostics.representativeMaximum, representativeMinimum: model.diagnostics.representativeMinimum,
  representativeMddPct: model.diagnostics.representativeMddPct, simulatedMddPct: model.diagnostics.simulatedMddPct,
  candidateBreakPaths: model.diagnostics.candidateLowBreakPathsBeforePeakReference, totalPaths: model.diagnostics.totalPaths,
  localTurnCount: model.localTurns.length, lastPoint: model.path.at(-1),
}));
const report = { version: 'detailed-forecast-results-1', informationThrough: options.asOf, referenceDate: options.referenceDate,
  referenceTimezone: 'Asia/Seoul', generatedBy: 'node scripts/analyze-detailed-forecast.mjs',
  priceSource: data.meta?.source, priceDefinition: data.meta?.priceDefinition,
  summary, validation, sensitivity, scenarios };
const filename = path.join(root, 'docs/DETAILED_FORECAST_RESULTS.json');
const serialized = `${JSON.stringify(report)}\n`;
await writeFile(filename, serialized);
const uiValidation = {
  version: 'detailed-validation-1', modelVersion: scenarios[0].version, informationThrough: options.asOf,
  appliesTo: { scenario: 'base', blockDays: 28, seed: options.seed, sampleCount: 64, priceGrowthRetention: 0.75, bearDrawdownPct: 50, volatilityMultiplier: 1 },
  outcomeThrough: validation.outcomeThrough, numberOfDistinctCutoffs: validation.numberOfDistinctCutoffs,
  effectiveMacroCohorts: validation.effectiveMacroCohorts, independentTrialCountClaim: null,
  overlappingOutcomes: true, genuineProspectiveValidation: false, parameterSelectionWasRetrospective: true,
  current2025And2026OutcomesIncluded: false, candidateHoldFailures: validation.candidateHoldFailures,
  summary: validation.summary, simpleBaselineDefinition: validation.simpleBaselineDefinition, warning: validation.warning,
};
const uiSensitivity = sensitivity.map(item => ({ group: item.group, parameters: item.parameters,
  firstLowMedianDate: item.firstTurnWindows.low.medianDate, firstLowLowerDate: item.firstTurnWindows.low.lowerDate, firstLowUpperDate: item.firstTurnWindows.low.upperDate,
  firstHighMedianDate: item.firstTurnWindows.high.medianDate, firstHighLowerDate: item.firstTurnWindows.high.lowerDate, firstHighUpperDate: item.firstTurnWindows.high.upperDate,
  mddPct: item.mddPct, candidateBreakPaths: item.candidateBreakPaths, totalPaths: item.totalPaths,
  horizonEndRange: { lower: item.lastPoint.lower, median: item.lastPoint.median, upper: item.lastPoint.upper }, probability: null,
}));
await writeFile(path.join(root, 'dist/forecast-validation.js'),
  `// Generated by node scripts/analyze-detailed-forecast.mjs. All scores are retrospective.\nexport const FORECAST_VALIDATION = ${JSON.stringify(uiValidation, null, 2)};\n\nexport const FORECAST_SENSITIVITY = ${JSON.stringify(uiSensitivity, null, 2)};\n`);
console.log(JSON.stringify({ file: path.relative(root, filename), bytes: Buffer.byteLength(serialized), scenarios: scenarios.length, dailyRowsPerScenario: scenarios[0].path.length,
  sampleCount: options.sampleCount, validationCutoffs: validation.numberOfDistinctCutoffs, effectiveMacroCohorts: validation.effectiveMacroCohorts,
  validationSummary: validation.summary.map(item => ({ horizon: item.horizon, n: item.samples, distinctMacroCohorts: item.distinctMacroCohorts, medianMAPEPct: item.median.mapePct, flatMAPEPct: item.flat.mapePct, simpleMAPEPct: item.simpleCalendarBaseline.mapePct, empiricalEnvelopeCovered: item.envelopeCovered })) }, null, 2));
