import assert from 'node:assert/strict';
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const input = JSON.parse(await readFile(path.join(root, 'research-data/permitted-source-texts.json'), 'utf8'));
const digest = body => createHash('sha256').update(body).digest('hex');

async function readVerified(record) {
  assert.match(record.path, /^dist\/research-sources\/[A-Za-z0-9-]+\.md$/);
  const body = await readFile(path.join(root, record.path));
  assert.equal(body.length, record.bytes, `Source byte length changed: ${record.path}`);
  assert.equal(digest(body), record.sha256, `Source SHA-256 changed: ${record.path}`);
  const gitSha = createHash('sha1').update(`blob ${body.length}\0`).update(body).digest('hex');
  assert.equal(gitSha, record.gitBlobSha, `Upstream Git blob differs: ${record.path}`);
  const text = new TextDecoder('utf-8', {fatal: true}).decode(body);
  assert.deepEqual(Buffer.from(text), body, `UTF-8 round trip changed: ${record.path}`);
  return text;
}

assert.equal(input.license.id, 'CC0-1.0');
assert.ok(Number.isFinite(Date.parse(input.retrievedAt)));
const licenseText = await readVerified(input.license);
assert.ok(licenseText.includes('CC0 1.0 Universal'));
const sources = [];
const ids = new Set(), urls = new Set();
for (const record of input.sources) {
  assert.match(record.id, /^eip-[1-9][0-9]*$/);
  assert.ok(!ids.has(record.id) && !urls.has(record.sourceUrl), 'Duplicate permitted source');
  ids.add(record.id); urls.add(record.sourceUrl);
  assert.match(record.sourceRevision, /^[a-f0-9]{40}$/);
  assert.equal(record.sourcePath, `EIPS/${record.id}.md`);
  assert.equal(record.sourceUrl, `https://eips.ethereum.org/EIPS/${record.id}`);
  assert.equal(record.versionedUrl, `https://github.com/ethereum/EIPs/blob/${record.sourceRevision}/${record.sourcePath}`);
  assert.equal(record.rawUrl, `https://raw.githubusercontent.com/ethereum/EIPs/${record.sourceRevision}/${record.sourcePath}`);
  assert.equal(record.licenseUrl, `https://github.com/ethereum/EIPs/blob/${record.sourceRevision}/LICENSE.md`);
  const text = await readVerified(record);
  assert.match(text, /## Copyright\s+Copyright and related rights waived via \[CC0\]\(\.\.\/LICENSE\.md\)\.\s*$/);
  sources.push({...record, license: input.license.id, retrievedAt: input.retrievedAt, completeSourceText: true, mediaBytesArchived: false, text});
}

const manifest = {...input, license: {...input.license}, sources: sources.map(({text, ...record}) => record)};
const outputs = [
  ['dist/research-source-data.js', `// Generated by scripts/build-research-sources.mjs\nexport const RESEARCH_SOURCES=${JSON.stringify(sources)};\n`],
  ['dist/research-sources/manifest.json', `${JSON.stringify(manifest, null, 2)}\n`],
];
for (const [file, body] of outputs) {
  if (check) assert.equal(await readFile(path.join(root, file), 'utf8'), body, `Stale ${file}`);
  else await writeFile(path.join(root, file), body);
}
console.log(JSON.stringify({status: 'ok', check, sources: sources.length, originalBytes: sources.reduce((n, source) => n + source.bytes, 0), licenseBytes: input.license.bytes}));
